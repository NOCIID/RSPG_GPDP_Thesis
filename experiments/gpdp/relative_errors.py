"""
Relative errors in consumption-equivalent (CE) units, for every method, next to exploitability.

Raw value ratios explode when values are close to zero. Instead, each value is turned into the
constant consumption c_bar that gives the same lifetime utility: with CRRA utility (no additive shift),
V = const * u(c_bar), so  c_bar_a / c_bar_b = (V_a / V_b)^(1 / (1 - sigma))  (sigma = 2: V_b / V_a).
Consumption has a meaningful zero and the right scale (as eq. (2) of the 2026-10-06 report and
check_critic.py).

For each run, on 64 held-out economies (key 777, as compare_runs.py / step4_evaluate.py) generated by
the run's own policy, against four best responses (BR):
    clairvoyant / honest (knows the realized shocks / follows value GPs that do not)
  x continuous shares / the 20 grid actions
  - value relative error, per individual state x and period t:  |c_bar_policy / c_bar_BR - 1|
      * at t = 0 weighted by mu_0 (the weighting of MFAX's exploitability)
      * over all periods weighted by mu_t (where households are)
      * max over visited states (mu_t > 1e-4)
  - policy relative error: |c_policy / c_BR - 1| = |share_policy / share_BR - 1| (same cash on hand;
    mixed policies use their mean share), over periods 0 .. T-2 weighted by mu_t, max over visited states
  - the aggregate gain from deviating (CE of the mu_0-weighted mean values), as reported before

Safety check: the mixed-policy values here reproduce MFAX's evaluate_given_sequence at t = 0.

    python experiments/gpdp/relative_errors.py --runs runs/endogenous/gpdp/const15_a05_s0 ...
"""

import argparse
import json
import pickle
import sys
from pathlib import Path

import jax
import jax.numpy as jnp
import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from mfax.algos.hsm.evaluate import evaluate_given_sequence  # noqa: E402
from mfax.algos.hsm.sequence import mf_sequence  # noqa: E402
from mfax.algos.hsm.utils import gpdp_backward as gb  # noqa: E402
from mfax.algos.hsm.utils import gpdp_continuous as gc  # noqa: E402
from mfax.algos.hsm.utils import gpdp_train as gt  # noqa: E402
from mfax.envs import make_env  # noqa: E402

VISITED = 1e-4
BLOCKS = [(0, 32), (32, 64), (64, 96), (96, 112), (112, 120), (120, 127)]  # periods; the last decision is at 126


def mixture_values(env, traj, gamma):
    """Values of a mixed (prob_a) policy along MFAX sequences, every period: (T, E, n_states)."""
    E = traj.aggregate_s.mu.shape[1]

    def _one_period(v_next, inputs):
        aggregate_s, prob_a, mat_r = inputs
        v = jnp.sum(prob_a * mat_r, axis=-1) + gamma * jax.vmap(env.mf_expected_value)(
            v_next, prob_a, aggregate_s
        )
        return v, v

    _, V = jax.lax.scan(
        _one_period,
        jnp.zeros((E, env.n_states)),
        (traj.aggregate_s, traj.prob_a, traj.mat_r),
        reverse=True,
    )
    return V


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--runs", nargs="+", required=True)
    p.add_argument("--eval-envs", type=int, default=64)
    p.add_argument("--eval-seed", type=int, default=777)
    p.add_argument("--stations", type=int, default=8)
    p.add_argument("--station-seed", type=int, default=4242)
    p.add_argument("--out", default="relative_errors.json")
    cli = p.parse_args()

    env = make_env("pushforward/endogenous", common_noise=True)
    gamma, sigma, T = 0.95, env.params.sigma, env.params.max_steps_in_episode
    key = jax.random.PRNGKey(cli.eval_seed)
    path_value = jax.jit(lambda a, s: gc.path_evaluate(env, a, s, gamma))
    br_cont = jax.jit(lambda a: gc.path_best_response(env, a, gamma)[1])
    br_grid = jax.jit(lambda a: gc.path_best_response(env, a, gamma, grid_only=True)[1])
    mix_values = jax.jit(lambda traj: mixture_values(env, traj, gamma))
    c_ratio = lambda va, vb: (va / vb) ** (1 / (1 - sigma))  # noqa: E731  (c_bar_a / c_bar_b)
    out = dict(eval_envs=cli.eval_envs, eval_seed=cli.eval_seed, runs={})

    for run_dir in cli.runs:
        run_dir = Path(run_dir)
        run_args = json.loads((run_dir / "args.json").read_text())
        is_gpdp = (run_dir / "gpdp_agent.pkl").exists()
        with open(run_dir / ("gpdp_agent.pkl" if is_gpdp else "mf_agent_wrapper.pkl"), "rb") as f:
            agent = pickle.load(f)
        continuous = is_gpdp and not run_args.get("grid_actions", False)
        name = f"{run_dir.parent.name}/{run_dir.name}"

        # --- the run's economy, its policy's values (every period) and mean shares ---
        if continuous:
            seq, shares = gt.forward(env, agent.mf_params, key, cli.eval_envs)[:2]
            V_pol = path_value(seq, shares)
            stations = gt.forward(env, agent.mf_params, jax.random.PRNGKey(cli.station_seed), cli.stations)[0]
            check = None
        else:
            traj = mf_sequence(key, env, agent, "states", cli.eval_envs, T)
            seq = traj.aggregate_s
            V_pol = mix_values(traj)
            shares = (traj.prob_a * env.params.discrete_actions).sum(-1)
            stations = mf_sequence(jax.random.PRNGKey(cli.station_seed), env, agent, "states", cli.stations, T).aggregate_s
            v_mfax, _ = evaluate_given_sequence(env, traj, gamma=gamma)
            check = float(jnp.abs(V_pol[0] / v_mfax - 1).max())

        # --- best responses: shares, then their values along the same paths ---
        gps_c, _, _, _ = gb.backward_pass(env, stations, gamma)
        gps_g, _, _, _ = gb.backward_pass(env, stations, gamma, grid_only=True)
        br_shares = dict(
            clairvoyant_continuous=br_cont(seq),
            clairvoyant_grid=br_grid(seq),
            honest_continuous=gb.greedy_shares(env, seq, gps_c, gamma),
            honest_grid=gb.greedy_shares(env, seq, gps_g, gamma, grid_only=True),
        )

        mu = np.asarray(seq.mu)  # (T, E, n)
        w_t = mu / mu.sum(-1, keepdims=True)
        visited = mu > VISITED
        V_pol_np, shares_np = np.asarray(V_pol), np.asarray(shares)
        res = dict(mixed_policy_vs_mfax_evaluate_max_rel_diff=check, by_best_response={})
        for kind, s_br in br_shares.items():
            V_br = np.asarray(path_value(seq, s_br))
            val_err = np.abs(c_ratio(V_pol_np, V_br) - 1)  # (T, E, n)
            pol_err = np.abs(shares_np[: T - 1] / np.asarray(s_br)[: T - 1] - 1)
            gain = 100 * (c_ratio((V_br[0] * mu[0]).sum(-1).mean(), (V_pol_np[0] * mu[0]).sum(-1).mean()) - 1)
            res["by_best_response"][kind] = dict(
                gain_from_deviating_pct=float(gain),
                value_relerr_t0_mu0_weighted_pct=100 * float((w_t[0] * val_err[0]).sum(-1).mean()),
                value_relerr_all_periods_pop_weighted_pct=100 * float((w_t * val_err).sum(-1).mean()),
                value_relerr_visited_max_pct=100 * float(val_err[visited].max()),
                policy_relerr_pop_weighted_pct=100 * float((w_t[: T - 1] * pol_err).sum(-1).mean()),
                policy_relerr_visited_max_pct=100 * float(pol_err[visited[: T - 1]].max()),
                # --- where in the episode the errors are (population-weighted, by period block) ---
                value_relerr_by_block_pct={
                    f"{a}-{b - 1}": 100 * float((w_t[a:b] * val_err[a:b]).sum(-1).mean()) for a, b in BLOCKS
                },
                policy_relerr_by_block_pct={
                    f"{a}-{b - 1}": 100 * float((w_t[a:b] * pol_err[a:b]).sum(-1).mean()) for a, b in BLOCKS
                },
            )
        out["runs"][name] = res
        hc, hg = res["by_best_response"]["honest_continuous"], res["by_best_response"]["honest_grid"]
        print(
            f"{name:34s} value rel. err (honest cont / grid, t=0 mu0): {hc['value_relerr_t0_mu0_weighted_pct']:.3f}% / "
            f"{hg['value_relerr_t0_mu0_weighted_pct']:.3f}%   policy rel. err: {hc['policy_relerr_pop_weighted_pct']:.2f}% / "
            f"{hg['policy_relerr_pop_weighted_pct']:.2f}%   check {check}",
            flush=True,
        )

    path = Path(__file__).parent / "results" / cli.out
    path.write_text(json.dumps(out, indent=2))
    print(f"Saved {path}")


if __name__ == "__main__":
    main()
