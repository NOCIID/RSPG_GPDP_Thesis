"""
GPDP build step 1: what does the 20-action grid cost a household?

On economy paths generated by a trained policy (default: the RSPG + GP critic run gpfix_s0), solve the
household problem by backward induction twice: on the 20 grid actions (what MFAX's best response
does) and with continuous consumption shares (golden-section search). No GP and no learning: both
best responses use the realized paths, exactly like mfax.algos.hsm.best_response.br.

Safety net first (the new continuous code against MFAX's own code, where they overlap):
  A. the continuous push-forward step with shares equal to grid actions reproduces env.mf_step;
  B. the continuous best response restricted to the grid reproduces br().

    python experiments/gpdp/step1_continuous_br.py --run-dir runs/endogenous/hsm_rspg_gp/gpfix_s0
"""

import argparse
import json
import pickle
import sys
import time
from pathlib import Path

import jax
import jax.numpy as jnp
import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from mfax.algos.hsm.best_response import br  # noqa: E402
from mfax.algos.hsm.evaluate import evaluate_given_sequence  # noqa: E402
from mfax.algos.hsm.sequence import mf_sequence  # noqa: E402
from mfax.algos.hsm.utils import gpdp_continuous as gc  # noqa: E402
from mfax.envs import make_env  # noqa: E402


def at(tree, t, e):
    """Aggregate state of economy e at period t."""
    return jax.tree.map(lambda x: x[t, e], tree)


def check_forward(env, traj, key):
    """A: shares equal to grid actions vs env.mf_step with the corresponding one-hot prob_a."""
    t, e = 50, 0
    agg = at(traj.aggregate_s, t, e)
    k_act, k_step = jax.random.split(key)
    action_idx = jax.random.randint(k_act, (env.n_states,), 0, env.n_actions)
    prob_a = jax.nn.one_hot(action_idx, env.n_actions)
    shares = env.params.discrete_actions[action_idx]

    # --- MFAX: mf_step splits its key into (key_step, key_reset) and steps with key_step ---
    _, _, _, agg_env, mat_r, _, _, _ = env.mf_step(k_step, agg, prob_a)
    r_env = jnp.take_along_axis(mat_r, action_idx[:, None], axis=-1)[:, 0]
    key_step, _ = jax.random.split(k_step)
    agg_new, r_new, _ = gc.step(env, key_step, agg, shares)
    return dict(
        mu_max_abs_diff=float(jnp.abs(agg_env.mu - agg_new.mu).max()),
        mu_sum=float(agg_new.mu.sum()),
        z_abs_diff=float(jnp.abs(agg_env.z - agg_new.z)),
        prices_max_abs_diff=float(
            max(jnp.abs(agg_env.interest_rate - agg_new.interest_rate), jnp.abs(agg_env.wage - agg_new.wage))
        ),
        reward_max_abs_diff=float(jnp.abs(r_env - r_new).max()),
    )


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--run-dir", default="runs/endogenous/hsm_rspg_gp/gpfix_s0")
    p.add_argument("--envs", type=int, default=8)
    p.add_argument("--seed", type=int, default=777)
    p.add_argument("--n-iter", type=int, default=30, help="golden-section iterations")
    p.add_argument("--out", default="step1_continuous_br.json")
    cli = p.parse_args()

    run_dir = Path(cli.run_dir)
    run_args = json.loads((run_dir / "args.json").read_text())
    with open(run_dir / "mf_agent_wrapper.pkl", "rb") as f:
        wrapper = pickle.load(f)
    env = make_env("pushforward/endogenous", common_noise=True)
    gamma = run_args["discount_factor"]
    sigma = env.params.sigma
    T = env.params.max_steps_in_episode
    grid = np.asarray(env.params.discrete_actions)
    out = dict(run_dir=str(run_dir), envs=cli.envs, seed=cli.seed, n_iter=cli.n_iter)

    # --- the economy paths: the trained policy's own episodes ---
    traj = mf_sequence(jax.random.PRNGKey(cli.seed), env, wrapper, run_args["state_type"], cli.envs, T)
    mu0 = np.asarray(traj.aggregate_s.mu[0])  # (E, n_states)

    # --- A: forward step ---
    out["check_A_forward"] = check_forward(env, traj, jax.random.PRNGKey(0))
    print("A. forward step vs env.mf_step:", out["check_A_forward"], flush=True)

    # --- B: grid-restricted continuous code vs br() ---
    v_br, _, a_br, _ = br(env, traj, gamma)
    br_grid = jax.jit(lambda s: gc.path_best_response(env, s, gamma, grid_only=True))
    v_grid, s_grid = br_grid(traj.aggregate_s)
    out["check_B_best_response"] = dict(
        value_max_rel_diff=float(jnp.abs(v_grid / v_br - 1).max()),
        same_action_share=float((s_grid == env.params.discrete_actions[a_br]).mean()),
    )
    print("B. grid-restricted best response vs br():", out["check_B_best_response"], flush=True)

    # --- the comparison: continuous vs grid best response on the same paths ---
    br_cont = jax.jit(lambda s: gc.path_best_response(env, s, gamma, n_iter=cli.n_iter))
    v_cont, s_cont = br_cont(traj.aggregate_s)  # compile
    jax.block_until_ready(v_cont)
    t0 = time.perf_counter()
    v_cont, s_cont = jax.block_until_ready(br_cont(traj.aggregate_s))
    out["continuous_br_time_s"] = time.perf_counter() - t0
    v_grid, v_cont, s_grid, s_cont = map(np.asarray, (v_grid, v_cont, s_grid, s_cont))
    v_pol, _ = evaluate_given_sequence(env, traj, gamma=gamma)
    v_pol = np.asarray(v_pol)

    def weighted(v):  # as in MFAX's exploitability: mu_0-weighted, averaged over economies
        return float((v * mu0).sum(-1).mean())

    pol, grid_br, cont_br = weighted(v_pol), weighted(v_grid), weighted(v_cont)
    ce = lambda v_hi, v_lo: (v_hi / v_lo) ** (1 / (1 - sigma)) - 1  # noqa: E731
    out["values_mu0_weighted"] = dict(policy=pol, grid_br=grid_br, continuous_br=cont_br)
    out["exploitability"] = dict(
        vs_grid_br=grid_br - pol,
        vs_continuous_br=cont_br - pol,
        gain_from_deviating_pct_grid=100 * ce(grid_br, pol),
        gain_from_deviating_pct_continuous=100 * ce(cont_br, pol),
    )
    gain = ce(v_cont, v_grid)  # per state and economy, consumption-equivalent
    out["continuous_over_grid_ce_gain_pct"] = dict(
        mu0_weighted_mean=100 * float((gain * mu0).sum(-1).mean()),
        max=100 * float(gain.max()),
    )

    # --- shares where households actually are (period 64) ---
    t = 64
    mu_t = np.asarray(traj.aggregate_s.mu[t])
    w = mu_t / mu_t.sum(-1, keepdims=True)
    nearest_gap = np.abs(s_cont[t][..., None] - grid).min(-1)
    pol_share = np.asarray((traj.prob_a[t] * env.params.discrete_actions).sum(-1))
    out["period_64"] = dict(
        mean_share_policy=float((w * pol_share).sum(-1).mean()),
        mean_share_grid_br=float((w * s_grid[t]).sum(-1).mean()),
        mean_share_continuous_br=float((w * s_cont[t]).sum(-1).mean()),
        mass_with_continuous_share_off_grid_by_more_than_0_01=float((w * (nearest_gap > 0.01)).sum(-1).mean()),
    )

    # --- a few example households at period 64, economy 0 ---
    wealth, income = np.asarray(env.params.discrete_states[0]), np.asarray(env.params.discrete_states[1])
    examples = {}
    for name, (w_target, i_idx) in dict(
        poor=(0.5, 0), middle=(26.0, 2), rich=(90.0, 4)
    ).items():
        w_idx = int(np.abs(wealth - w_target).argmin())
        s_idx = w_idx * len(income) + i_idx
        examples[name] = dict(
            wealth=float(wealth[w_idx]),
            income=float(income[i_idx]),
            policy_mean_share=float(pol_share[0, s_idx]),
            grid_best_share=float(s_grid[t, 0, s_idx]),
            continuous_best_share=float(s_cont[t, 0, s_idx]),
            ce_gain_pct_at_t0=100 * float(gain[0, s_idx]),
        )
    out["examples_period_64_economy_0"] = examples

    print(json.dumps({k: v for k, v in out.items() if not k.startswith("check")}, indent=2))
    path = Path(__file__).parent / "results" / cli.out
    path.parent.mkdir(exist_ok=True)
    path.write_text(json.dumps(out, indent=2))
    print(f"Saved {path}")


if __name__ == "__main__":
    main()
