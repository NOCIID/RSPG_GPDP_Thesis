"""
GPDP build step 4: held-out evaluation of GPDP runs and of the RSPG baselines, on the same footing.

For each run, on 64 held-out economies (key 777, as compare_runs.py) generated by the run's own policy:
  - MFAX's exploitability: best response on the 20 grid actions, knowing the realized shocks
    (exactly compare_runs.py's number). GPDP enters through GPDPAgent (shares split onto the grid).
  - Continuous, clairvoyant: best response with continuous shares, knowing the realized shocks.
  - Continuous, honest: best response from a GPDP backward pass against the run's policy (8 stations),
    following the value GPs, which never see future shocks.
Gains are in % of consumption (mu_0-weighted, as MFAX's exploitability).
For GPDP the continuous metrics use its own continuous economy (shares applied directly); for RSPG
runs, the economy their policy generates in MFAX.

    python experiments/gpdp/step4_evaluate.py --runs runs/endogenous/gpdp/const15_a05_s0 \
        runs/endogenous/hsm_rspg_gp/gpfix_s0 runs/endogenous/hsm_rspg_gp/base_s0
"""

import argparse
import json
import pickle
import sys
from pathlib import Path

import jax
import jax.numpy as jnp
import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from mfax.algos.hsm.evaluate import evaluate_given_sequence  # noqa: E402
from mfax.algos.hsm.exploitability import make_exploitability  # noqa: E402
from mfax.algos.hsm.sequence import mf_sequence  # noqa: E402
from mfax.algos.hsm.utils import gpdp_backward as gb  # noqa: E402
from mfax.algos.hsm.utils import gpdp_continuous as gc  # noqa: E402
from mfax.algos.hsm.utils import gpdp_train as gt  # noqa: E402
from mfax.algos.hsm.utils.gp_critic import aggregate_features  # noqa: E402
from mfax.envs import make_env  # noqa: E402


def load(run_dir):
    run_dir = Path(run_dir)
    run_args = json.loads((run_dir / "args.json").read_text())
    is_gpdp = (run_dir / "gpdp_agent.pkl").exists()
    with open(run_dir / ("gpdp_agent.pkl" if is_gpdp else "mf_agent_wrapper.pkl"), "rb") as f:
        agent = pickle.load(f)
    log = json.loads((run_dir / "log.json").read_text()) if (run_dir / "log.json").exists() else {}
    return dict(name=f"{run_dir.parent.name}/{run_dir.name}", args=run_args, agent=agent, gpdp=is_gpdp, log=log)


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--runs", nargs="+", required=True)
    p.add_argument("--eval-envs", type=int, default=64)
    p.add_argument("--eval-seed", type=int, default=777)
    p.add_argument("--stations", type=int, default=8)
    p.add_argument("--station-seed", type=int, default=4242)
    p.add_argument("--out", default="step4_evaluate.json")
    cli = p.parse_args()

    env = make_env("pushforward/endogenous", common_noise=True)
    gamma, sigma, T = 0.95, env.params.sigma, env.params.max_steps_in_episode
    ce = lambda hi, lo: 100 * ((hi / lo) ** (1 / (1 - sigma)) - 1)  # noqa: E731
    path_br = jax.jit(lambda a: gc.path_best_response(env, a, gamma)[0])
    path_value = jax.jit(lambda a, s: gc.path_evaluate(env, a, s, gamma)[0])
    key = jax.random.PRNGKey(cli.eval_seed)
    out = dict(eval_envs=cli.eval_envs, eval_seed=cli.eval_seed, runs={})

    for run_dir in cli.runs:
        run = load(run_dir)
        agent = run["agent"]

        # --- 1. MFAX's exploitability (as compare_runs.py); GPDP's shares put on the grid two ways ---
        def mfax_metric(a):
            res = make_exploitability(
                env=env, agent=a, state_type="states", gamma=gamma,
                num_envs=cli.eval_envs, max_steps_in_episode=T,
            )(key, a.mf_params)
            return dict(
                exploitability=float(res.exploitability.exploitability),
                gain_pct=ce(float(res.exploitability.mean_br_return), float(res.exploitability.mean_policy_return)),
            )

        mfax = mfax_metric(agent)
        if run["gpdp"]:
            mfax_nearest = mfax_metric(type(agent)(env, agent.mf_params, grid_mode="nearest"))

        # --- the run's economy (continuous for GPDP, MFAX's for RSPG) and its stations ---
        grid_trained = run["args"].get("grid_actions", False)
        if run["gpdp"] and not grid_trained:
            seq, shares = gt.forward(env, agent.mf_params, key, cli.eval_envs)[:2]
            v_pol = path_value(seq, shares)
            stations = gt.forward(env, agent.mf_params, jax.random.PRNGKey(cli.station_seed), cli.stations)[0]
        else:  # RSPG runs, and GPDP trained on the grid (its economy is MFAX's, as during training)
            traj = mf_sequence(key, env, agent, "states", cli.eval_envs, T)
            seq = traj.aggregate_s
            v_pol, _ = evaluate_given_sequence(env, traj, gamma=gamma)
            shares = (traj.prob_a * env.params.discrete_actions).sum(-1)  # mean share, for reporting
            stations = mf_sequence(jax.random.PRNGKey(cli.station_seed), env, agent, "states", cli.stations, T).aggregate_s
        mu0 = np.asarray(seq.mu[0])
        w = lambda v: float((np.asarray(v) * mu0).sum(-1).mean())  # noqa: E731
        pol = w(v_pol)

        # --- 2. continuous clairvoyant; 3. continuous honest (GPDP backward pass against this policy) ---
        clair = w(path_br(seq))
        gps, _, _, _ = gb.backward_pass(env, stations, gamma)
        honest = w(path_value(seq, gb.greedy_shares(env, seq, gps, gamma)))
        # --- 4. grid honest: best response among the 20 grid actions that does not see future shocks
        #     (MFAX's exploitability without the hindsight) ---
        gps_grid, _, _, _ = gb.backward_pass(env, stations, gamma, grid_only=True)
        honest_grid = w(path_value(seq, gb.greedy_shares(env, seq, gps_grid, gamma, grid_only=True)))

        def share_at(t):
            mu = np.asarray(seq.mu[t])
            return float((np.asarray(shares[t]) * mu / mu.sum(-1, keepdims=True)).sum(-1).mean())

        K = np.asarray(jax.vmap(lambda a: aggregate_features(env, a))(seq))[..., 1].mean(-1)
        timing = run["log"].get("timing", {})
        out["runs"][run["name"]] = dict(
            method=("gpdp_grid" if grid_trained else "gpdp") if run["gpdp"] else run["args"].get("algo"),
            mfax=mfax,
            mfax_nearest_grid=mfax_nearest if run["gpdp"] else None,
            gain_continuous_clairvoyant_pct=ce(clair, pol),
            gain_continuous_honest_pct=ce(honest, pol),
            gain_grid_honest_pct=ce(honest_grid, pol),
            policy_value=pol,
            train_time_s=run["log"].get("train_time", timing.get("total_train_time")),
            K_mean_at={str(t): float(K[t]) for t in (0, 25, 50, 100, 127)},
            mean_share_at={str(t): share_at(t) for t in (0, 64, 100, 120, 126)},
        )
        r = out["runs"][run["name"]]
        nearest = f"  nearest-grid {mfax_nearest['exploitability']:.4f} ({mfax_nearest['gain_pct']:.3f}%)" if run["gpdp"] else ""
        print(
            f"{r['method']:12s} {run['name']:32s} MFAX expl {mfax['exploitability']:.4f} ({mfax['gain_pct']:.3f}%){nearest}  "
            f"continuous clairvoyant {r['gain_continuous_clairvoyant_pct']:.3f}%  honest {r['gain_continuous_honest_pct']:.3f}%  grid honest {r['gain_grid_honest_pct']:.3f}%  "
            f"K100 {r['K_mean_at']['100']:.1f}",
            flush=True,
        )

    path = Path(__file__).parent / "results" / cli.out
    path.write_text(json.dumps(out, indent=2))
    print(f"Saved {path}")


if __name__ == "__main__":
    main()
